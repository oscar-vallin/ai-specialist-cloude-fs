#!/usr/bin/env python3
"""Generates backend/src/main/resources/db/seed/V1000__local_seed.sql from books.json.

Deterministic: the same books.json always produces the same SQL (UUIDs, ISBNs, prices, weights and stock are all
derived from the data with hashing, never from a random generator or the clock).
Only the local/dev profiles load the output (application-local.properties). Never run it from the app or the build.

Usage: python3 generate_seed.py [BCRYPT_HASH_ADMIN] [BCRYPT_HASH_CUSTOMER]
Hashes default to bcrypt('AdminLocal#2026') and bcrypt('CustomerLocal#2026'), documented in the README for local use.
"""
import hashlib
import json
import sys
import uuid
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parent / "src/main/resources/db/seed/V1000__local_seed.sql"
NS = uuid.UUID("b00c5701-0000-4000-8000-000000000001")

ADMIN_HASH = sys.argv[1] if len(sys.argv) > 1 else "ADMIN_HASH_PLACEHOLDER"
CUSTOMER_HASH = sys.argv[2] if len(sys.argv) > 2 else "CUSTOMER_HASH_PLACEHOLDER"


def uid(kind, key):
    return str(uuid.uuid5(NS, f"{kind}:{key}"))


def q(value):
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def h(text):
    return int(hashlib.sha256(text.encode()).hexdigest(), 16)


def isbn13(index):
    body = "978" + "1" + f"{900000 + index * 37:08d}"[:8]
    body = body[:12]
    total = sum(int(d) * (1 if i % 2 == 0 else 3) for i, d in enumerate(body))
    return body + str((10 - total % 10) % 10)


def hyphenate(isbn):
    return f"{isbn[:3]}-{isbn[3]}-{isbn[4:8]}-{isbn[8:12]}-{isbn[12]}"


def slug(text):
    return "".join(c.lower() if c.isalnum() else "-" for c in text).strip("-")


data = json.loads((HERE / "books.json").read_text())
lines = []
w = lines.append

STORE = uid("store", "Main Store")
CATALOG_PUBLIC = uid("catalog", "public")
CATALOG_MEMBERS = uid("catalog", "members")

w("-- GENERATED by backend/seed/generate_seed.py from backend/seed/books.json. Do not edit by hand.")
w("-- LOCAL/DEV ONLY (loaded by the 'local' profile through spring.flyway.locations). Never deploy to production.")
w("-- Dev credentials are documented in the README and are for local development only.")
w("")
w("INSERT INTO stores (id, name) VALUES (%s, 'Main Store');" % q(STORE))
w("INSERT INTO store_policies (store_id, cancellation_window_hours, return_window_days, free_shipping_threshold,"
  " tax_rate, gift_points_per_currency_unit, max_gift_points_percent)")
w("VALUES (%s, 48, 7, 50.00, 0.0800, ${giftpoints}, 100);" % q(STORE))
w("INSERT INTO catalogs (id, store_id, name) VALUES (%s, %s, 'Main Catalog'), (%s, %s, 'Members Catalog');"
  % (q(CATALOG_PUBLIC), q(STORE), q(CATALOG_MEMBERS), q(STORE)))
w("-- The Members Catalog is visible only to CUSTOMER and ADMIN; the Main Catalog has no entitlement rows (everyone).")
w("INSERT INTO catalog_entitlements (catalog_id, role_id) SELECT %s, id FROM roles WHERE name IN ('CUSTOMER', 'ADMIN');"
  % q(CATALOG_MEMBERS))
w("")

# categories (parents first)
order = 0
for c in data["categories"]:
    order += 1
    parent = "NULL" if c["parent"] is None else q(uid("category", c["parent"]))
    w("INSERT INTO categories (id, parent_id, name, slug, display_order) VALUES (%s, %s, %s, %s, %d);"
      % (q(uid("category", c["slug"])), parent, q(c["name"]), q(c["slug"]), order))
w("")
for b in data["brands"]:
    w("INSERT INTO brands (id, name, description) VALUES (%s, %s, %s);"
      % (q(uid("brand", b["name"])), q(b["name"]), q(b["description"])))
w("")

authors = {}
for book in data["books"]:
    for a in book["authors"]:
        authors.setdefault(a, uid("author", a))
for name, aid in authors.items():
    w("INSERT INTO authors (id, name) VALUES (%s, %s);" % (q(aid), q(name)))
w("")

FORMAT_BASE = {"PAPERBACK": 1099, "HARDCOVER": 1899, "EBOOK": 699}
FORMAT_WEIGHT = {"PAPERBACK": 350, "HARDCOVER": 780, "EBOOK": None}
product_ids = []
for i, book in enumerate(data["books"], start=1):
    pid = uid("product", book["title"])
    product_ids.append(pid)
    isbn = hyphenate(isbn13(i))
    cents = FORMAT_BASE[book["format"]] + (h(book["title"]) % 900)
    price = f"{cents // 100}.{cents % 100:02d}"
    weight = FORMAT_WEIGHT[book["format"]]
    if weight is not None:
        weight += h(book["title"] + "w") % 300
    language = "en"
    w("INSERT INTO products (id, isbn, title, tagline, description, format, language, price, brand_id, cover_front_url,"
      " cover_back_url, weight_grams, publication_date, status)")
    w("VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, NULL, %s, %s, 'ACTIVE');"
      % (q(pid), q(isbn), q(book["title"]), q(book.get("tagline")), q(book.get("description")), q(book["format"]),
         q(language), price, q(uid("brand", book["brand"])), q("/covers/%s.svg" % slug(book["title"])),
         "NULL" if weight is None else weight,
         q("%d-%02d-%02d" % (book["year"], 1 + h(book["title"] + "m") % 12, 1 + h(book["title"] + "d") % 28))))
    for order_, a in enumerate(book["authors"], start=1):
        w("INSERT INTO product_authors (product_id, author_id, author_order) VALUES (%s, %s, %d);"
          % (q(pid), q(authors[a]), order_))
    w("INSERT INTO product_categories (product_id, category_id, is_primary) VALUES (%s, %s, TRUE);"
      % (q(pid), q(uid("category", book["category"]))))
    for extra in book.get("extra", []):
        w("INSERT INTO product_categories (product_id, category_id, is_primary) VALUES (%s, %s, FALSE);"
          % (q(pid), q(uid("category", extra))))
    catalog = CATALOG_MEMBERS if book.get("members_only") else CATALOG_PUBLIC
    w("INSERT INTO catalog_products (catalog_id, product_id) VALUES (%s, %s);" % (q(catalog), q(pid)))
    if book["format"] != "EBOOK":
        # A few titles are deliberately low or out of stock to exercise stock rules by hand.
        stock = 0 if i % 17 == 0 else (3 if i % 11 == 0 else 20 + h(book["title"] + "s") % 60)
        w("INSERT INTO inventory (product_id, quantity_available) VALUES (%s, %d);" % (q(pid), stock))
    w("")

# related products: next two books of the same primary category
by_cat = {}
for book, pid in zip(data["books"], product_ids):
    by_cat.setdefault(book["category"], []).append(pid)
for cat, pids in by_cat.items():
    for idx, pid in enumerate(pids):
        for pos, other in enumerate([p for p in pids if p != pid][:2]):
            w("INSERT INTO related_products (product_id, related_product_id, relation_type, position) VALUES (%s, %s, %s, %d);"
              % (q(pid), q(other), q("RELATED" if pos == 0 else "CROSS_SELL"), pos))
w("")

# shipping rates for US and CA (weight bands in grams, lower bound inclusive)
bands = [(0, 500, "3.99", 3, 5), (500, 1000, "5.99", 3, 6), (1000, 2000, "8.99", 4, 7), (2000, 20000, "14.99", 5, 9)]
for country, extra_days in (("US", 0), ("CA", 2)):
    for lo, hi, rate, dmin, dmax in bands:
        w("INSERT INTO shipping_rates (store_id, country, min_weight_grams, max_weight_grams, rate, estimated_days_min,"
          " estimated_days_max) VALUES (%s, %s, %d, %d, %s, %d, %d);"
          % (q(STORE), q(country), lo, hi, rate, dmin + extra_days, dmax + extra_days))
w("")

# coupons
w("INSERT INTO coupons (store_id, code, discount_type, discount_value, min_order_amount, max_redemptions, active)"
  " VALUES (%s, 'WELCOME10', 'PERCENT', 10.00, 20.00, NULL, TRUE);" % q(STORE))
w("INSERT INTO coupons (store_id, code, discount_type, discount_value, min_order_amount, max_redemptions, active)"
  " VALUES (%s, 'SAVE5', 'FIXED', 5.00, 30.00, 100, TRUE);" % q(STORE))
w("INSERT INTO coupons (store_id, code, discount_type, discount_value, active)"
  " VALUES (%s, 'EXPIRED', 'PERCENT', 20.00, FALSE);" % q(STORE))
w("")

# dev users
ADMIN = uid("user", "admin@bookstore.local")
CUSTOMER = uid("user", "customer@bookstore.local")
for uid_, email, first, last, pw, role in (
        (ADMIN, "admin@bookstore.local", "Ada", "Admin", ADMIN_HASH, "ADMIN"),
        (CUSTOMER, "customer@bookstore.local", "Carla", "Customer", CUSTOMER_HASH, "CUSTOMER")):
    w("INSERT INTO users (id, email, password_hash, first_name, last_name) VALUES (%s, %s, %s, %s, %s);"
      % (q(uid_), q(email), q(pw), q(first), q(last)))
    w("INSERT INTO user_roles (user_id, role_id) SELECT %s, id FROM roles WHERE name = %s;" % (q(uid_), q(role)))
    w("INSERT INTO wallets (user_id, balance) VALUES (%s, %s);" % (q(uid_), "50.00" if role == "CUSTOMER" else "0.00"))
    w("INSERT INTO gift_point_accounts (user_id, balance) VALUES (%s, %d);" % (q(uid_), 2000 if role == "CUSTOMER" else 0))
    if role == "CUSTOMER":
        w("INSERT INTO gift_point_ledger (user_id, points, type, balance_after) VALUES (%s, 2000, 'ADJUSTMENT', 2000);" % q(uid_))
        w("INSERT INTO wallet_transactions (wallet_id, type, amount, reason, balance_after)"
          " SELECT id, 'CREDIT', 50.00, 'ADJUSTMENT', 50.00 FROM wallets WHERE user_id = %s;" % q(uid_))
ADDRESS = uid("address", "customer-home")
w("INSERT INTO addresses (id, user_id, label, first_name, last_name, line1, city, state, postal_code, country, email, is_default)"
  " VALUES (%s, %s, 'Home', 'Carla', 'Customer', '123 Maple Street', 'Springfield', 'IL', '62701', 'US',"
  " 'customer@bookstore.local', TRUE);" % (q(ADDRESS), q(CUSTOMER)))
w("INSERT INTO addresses (user_id, label, first_name, last_name, line1, city, state, postal_code, country, is_default)"
  " VALUES (%s, 'Admin office', 'Ada', 'Admin', '1 Admin Plaza', 'Springfield', 'IL', '62701', 'US', TRUE);" % q(ADMIN))
w("")

# Two sample orders for manual testing of the cancellation window, timed relative to when the seed is applied.
# Both are CONFIRMED and paid by a (mock) card; only brand and last four digits are stored.
def sample_order(key, number, confirmed_offset_hours, book_titles):
    oid = uid("order", key)
    items = []
    subtotal_cents = 0
    for title, qty in book_titles:
        book = next(b for b in data["books"] if b["title"] == title)
        cents = FORMAT_BASE[book["format"]] + (h(book["title"]) % 900)
        items.append((uid("product", title), book, cents, qty))
        subtotal_cents += cents * qty
    tax_cents = (subtotal_cents * 8 + 50) // 100
    shipping_cents = 0 if subtotal_cents >= 5000 else 399
    total_cents = subtotal_cents + tax_cents + shipping_cents
    money = lambda c: f"{c // 100}.{c % 100:02d}"
    w("-- %s: confirmed %s hours before the seed is applied" % (number, confirmed_offset_hours))
    w("INSERT INTO orders (id, order_number, user_id, store_id, status, currency, subtotal, tax_total, shipping_total,"
      " coupon_discount, total, ship_first_name, ship_last_name, ship_line1, ship_city, ship_state, ship_postal_code,"
      " ship_country, ship_email, placed_at, confirmed_at, cancel_deadline_at, idempotency_key, request_hash)")
    w("VALUES (%s, %s, %s, %s, 'CONFIRMED', 'USD', %s, %s, %s, 0.00, %s, 'Carla', 'Customer', '123 Maple Street',"
      " 'Springfield', 'IL', '62701', 'US', 'customer@bookstore.local',"
      " now() - interval '%s hours' - interval '5 minutes', now() - interval '%s hours',"
      " now() - interval '%s hours' + interval '48 hours', %s, 'seed');"
      % (q(oid), q(number), q(CUSTOMER), q(STORE), money(subtotal_cents), money(tax_cents), money(shipping_cents),
         money(total_cents), confirmed_offset_hours, confirmed_offset_hours, confirmed_offset_hours,
         q("seed-" + key)))
    allocated = 0
    for n, (pid, book, cents, qty) in enumerate(items):
        line = cents * qty
        tax = (line * tax_cents) // subtotal_cents if n < len(items) - 1 else tax_cents - allocated
        allocated += tax
        w("INSERT INTO order_items (order_id, product_id, title, isbn, unit_price, quantity, line_total, tax_amount)"
          " SELECT %s, %s, title, isbn, %s, %d, %s, %s FROM products WHERE id = %s;"
          % (q(oid), q(pid), money(cents), qty, money(line), money(tax), q(pid)))
    w("INSERT INTO order_status_history (order_id, from_status, to_status, changed_at, note)"
      " VALUES (%s, NULL, 'PENDING_PAYMENT', now() - interval '%s hours' - interval '5 minutes', 'Seeded');"
      % (q(oid), confirmed_offset_hours))
    w("INSERT INTO order_status_history (order_id, from_status, to_status, changed_at, note)"
      " VALUES (%s, 'PENDING_PAYMENT', 'CONFIRMED', now() - interval '%s hours', 'Seeded');"
      % (q(oid), confirmed_offset_hours))
    pay = uid("payment", key)
    w("INSERT INTO payments (id, order_id, method, status, amount, card_brand, card_last4, gateway_reference,"
      " idempotency_key, request_hash, processed_at)"
      " VALUES (%s, %s, 'CREDIT_CARD', 'CAPTURED', %s, 'VISA', '4242', %s, %s, 'seed', now() - interval '%s hours');"
      % (q(pay), q(oid), money(total_cents), q("mock_ch_seed_" + key), q("seed-pay-" + key), confirmed_offset_hours))
    w("INSERT INTO shipments (order_id, type, status, shipping_cost, estimated_delivery_date)"
      " VALUES (%s, 'OUTBOUND', 'CREATED', %s, current_date + 5);" % (q(oid), money(shipping_cents)))
    w("")
    for pid, book, cents, qty in items:
        if book["format"] != "EBOOK":
            w("-- stock for seeded order lines is already out of the shelf count")
            w("UPDATE inventory SET quantity_available = GREATEST(quantity_available - %d, 0) WHERE product_id = %s;"
              % (qty, q(pid)))


sample_order("expired-window", "BW-SEED-000001", 49,
             [("Pride and Prejudice", 1), ("Frankenstein", 1)])
sample_order("recent", "BW-SEED-000002", 2,
             [("Clean Services", 1), ("REST Without Regret", 1)])

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT, len(lines), "lines")
